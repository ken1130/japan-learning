export function toKatakana(s) {
  return s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
}

export function toHiragana(s) {
  return s.replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
}

function flatten(rows, group) {
  return rows.flatMap(([, cells]) => cells.filter(Boolean).map(([k, r]) => ({ k, r, group })));
}

/** 所有平假名項目 { k, r, group } */
export const HIRA_ITEMS = [...flatten(GOJUON, 'basic'), ...flatten(DAKUTEN, 'dakuten'), ...flatten(YOON, 'yoon')];
export const KATA_ITEMS = HIRA_ITEMS.map((it) => ({ ...it, k: toKatakana(it.k) }));

export function kanaInfo(k) {
  const isKata = /[゠-ヿ]/.test(k);
  return {
    origin: (isKata ? ORIGIN_KATA : ORIGIN_HIRA)[k] || null,
    example: (isKata ? EXAMPLE_KATA : EXAMPLE_HIRA)[k] || null,
    confusable: CONFUSABLE[k] || null,
  };
}

