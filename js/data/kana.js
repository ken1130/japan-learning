export function kanaToRomaji(input) {
  const s = toHiragana(input);
  let out = '';
  let geminate = false;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === 'っ') {
      geminate = true;
      continue;
    }
    if (ch === 'ー') {
      const m = out.match(/[aeiou](?=[^aeiou]*$)/);
      out += m ? m[0] : '';
      continue;
    }
    let r = ROMAJI[s.slice(i, i + 2)];
    if (r) i++;
    else r = ROMAJI[ch] ?? ch;
    if (geminate) {
      out += r.startsWith('ch') ? 't' : r[0];
      geminate = false;
    }
    out += r;
  }
  return out;
}
